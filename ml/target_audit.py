"""Is ``water_requirement_liters`` usable as ground truth?

The project brief says this column must not be accepted as observed crop water
requirement without validation. This module performs that validation. It runs
four independent tests and returns a verdict with the evidence attached, so the
decision is reproducible rather than editorial.

The tests
---------
``dimensional_consistency``
    A water volume must equal depth times area. One millimetre spread over one
    hectare is ten thousand litres, so the depth implied by the stated volume
    and field area has to land in the range a real irrigation event occupies.

``driver_correlation``
    Evapotranspiration is *caused* by radiation, temperature, humidity and
    wind. In any real record ET correlates strongly with them. Near-zero
    correlation with every driver at once is not noise; it means the column was
    not produced by an evaporating surface.

``marginal_distribution``
    Measured agronomic variables are not uniformly distributed. A whole table of
    variables that each pass a uniformity test over a neat round interval is the
    signature of independent random draws.

``generative_structure``
    If the values were generated by a formula, that formula should be
    recoverable. Fitting a log-linear model of the stated target against the
    stated inputs shows how much of the column is a deterministic function of
    the other columns, and reports the multipliers it implies.

Only the first test is decisive on its own. The verdict combines all four.
"""

from __future__ import annotations

import dataclasses
from typing import Any, Sequence

import numpy as np
import pandas as pd
from scipy import stats

from ml.logging_utils import get_logger

log = get_logger("target_audit")

LITRES_PER_MM_PER_HECTARE: float = 10_000.0

#: The depth a single irrigation application realistically delivers. Surface
#: methods wet the root zone by tens of millimetres; even the lightest drip
#: pulse is a fraction of a millimetre, not a thousandth of one.
PLAUSIBLE_EVENT_DEPTH_MM: tuple[float, float] = (0.5, 150.0)


@dataclasses.dataclass
class AuditFinding:
    """One test, its verdict, and the numbers behind it."""

    name: str
    passed: bool
    headline: str
    evidence: dict[str, Any] = dataclasses.field(default_factory=dict)


@dataclasses.dataclass
class TargetAuditResult:
    """All findings plus the overall decision."""

    findings: list[AuditFinding]
    usable_as_ground_truth: bool
    rationale: str

    def to_frame(self) -> pd.DataFrame:
        return pd.DataFrame(
            [
                {
                    "test": f.name,
                    "verdict": "PASS" if f.passed else "FAIL",
                    "finding": f.headline,
                }
                for f in self.findings
            ]
        )

    def to_dict(self) -> dict[str, Any]:
        return {
            "usable_as_ground_truth": self.usable_as_ground_truth,
            "rationale": self.rationale,
            "findings": [dataclasses.asdict(f) for f in self.findings],
        }


# --------------------------------------------------------------------------
# Individual tests
# --------------------------------------------------------------------------
def test_dimensional_consistency(
    frame: pd.DataFrame,
    *,
    volume_col: str = "water_requirement_liters",
    area_col: str = "field_area_ha",
    et_col: str = "evapotranspiration",
) -> AuditFinding:
    """Does the stated volume correspond to a physically possible water depth?"""
    volume = frame[volume_col].to_numpy(dtype=float)
    area_ha = frame[area_col].to_numpy(dtype=float)
    implied_depth_mm = volume / (area_ha * LITRES_PER_MM_PER_HECTARE)

    low, high = PLAUSIBLE_EVENT_DEPTH_MM
    in_range = float(np.mean((implied_depth_mm >= low) & (implied_depth_mm <= high)))

    # How far off is it, as a pure multiplier?
    et_volume = frame[et_col].to_numpy(dtype=float) * area_ha * LITRES_PER_MM_PER_HECTARE
    with np.errstate(divide="ignore", invalid="ignore"):
        ratio = np.where(et_volume > 0, volume / et_volume, np.nan)

    median_depth = float(np.nanmedian(implied_depth_mm))
    shortfall = low / median_depth if median_depth > 0 else float("inf")

    return AuditFinding(
        name="dimensional_consistency",
        passed=in_range > 0.5,
        headline=(
            f"median implied depth is {median_depth:.6f} mm per record, about "
            f"{shortfall:,.0f} times smaller than the lightest realistic "
            f"irrigation application ({low} mm); "
            f"{in_range:.2%} of rows fall in the plausible range"
        ),
        evidence={
            "median_implied_depth_mm": median_depth,
            "max_implied_depth_mm": float(np.nanmax(implied_depth_mm)),
            "min_implied_depth_mm": float(np.nanmin(implied_depth_mm)),
            "fraction_in_plausible_range": in_range,
            "plausible_range_mm": list(PLAUSIBLE_EVENT_DEPTH_MM),
            "median_ratio_to_et_volume": float(np.nanmedian(ratio)),
        },
    )


def test_driver_correlation(
    frame: pd.DataFrame,
    *,
    et_col: str = "evapotranspiration",
    drivers: Sequence[str] = ("temperature", "humidity", "solar_radiation", "wind_speed_kmh"),
    threshold: float = 0.15,
) -> AuditFinding:
    """Does the evapotranspiration column respond to its own physical drivers?"""
    rows = []
    for driver in drivers:
        if driver not in frame.columns:
            continue
        r, p = stats.pearsonr(frame[driver].to_numpy(dtype=float),
                              frame[et_col].to_numpy(dtype=float))
        rows.append({"driver": driver, "pearson_r": float(r), "p_value": float(p)})

    strongest = max((abs(row["pearson_r"]) for row in rows), default=0.0)
    return AuditFinding(
        name="driver_correlation",
        passed=strongest >= threshold,
        headline=(
            f"the strongest correlation between the stated evapotranspiration and "
            f"any of its physical drivers is |r| = {strongest:.4f}; a measured or "
            f"physically modelled ET series cannot be uncorrelated with radiation, "
            f"temperature, humidity and wind simultaneously"
        ),
        evidence={"correlations": rows, "threshold": threshold},
    )


def test_marginal_distributions(
    frame: pd.DataFrame,
    *,
    columns: Sequence[str] = (
        "temperature", "humidity", "rainfall_mm", "wind_speed_kmh",
        "solar_radiation", "field_area_ha", "crop_age_days",
        "soil_moisture_pct", "evapotranspiration",
    ),
    alpha: float = 0.01,
) -> AuditFinding:
    """Are the marginals indistinguishable from independent uniform draws?"""
    rows = []
    for column in columns:
        if column not in frame.columns:
            continue
        values = frame[column].to_numpy(dtype=float)
        low, high = float(np.min(values)), float(np.max(values))
        if high <= low:
            continue
        result = stats.kstest((values - low) / (high - low), "uniform")
        rows.append(
            {
                "column": column,
                "min": low,
                "max": high,
                "ks_statistic": float(result.statistic),
                "p_value": float(result.pvalue),
                "uniform_not_rejected": bool(result.pvalue > alpha),
            }
        )

    n_uniform = sum(r["uniform_not_rejected"] for r in rows)
    return AuditFinding(
        name="marginal_distribution",
        passed=n_uniform < max(1, len(rows) // 2),
        headline=(
            f"{n_uniform} of {len(rows)} numeric columns are statistically "
            f"indistinguishable from a uniform distribution over a round interval; "
            f"measured agronomic variables are not uniform"
        ),
        evidence={"tests": rows, "alpha": alpha, "n_uniform": n_uniform},
    )


def test_generative_structure(
    frame: pd.DataFrame,
    *,
    volume_col: str = "water_requirement_liters",
    area_col: str = "field_area_ha",
    et_col: str = "evapotranspiration",
    categorical_cols: Sequence[str] = ("crop_type", "growth_stage", "soil_type", "irrigation_method"),
) -> AuditFinding:
    """Can the target be recovered as a closed-form function of the other columns?

    A log-linear fit is used because a water-balance-style generator is
    multiplicative: volume proportional to depth times area times per-category
    multipliers. Rows sitting exactly on the minimum or maximum are dropped
    first, since a clipped value carries no information about the generator.
    """
    volume = frame[volume_col].to_numpy(dtype=float)
    lo, hi = float(np.min(volume)), float(np.max(volume))
    at_floor = int(np.sum(volume <= lo * 1.001))
    at_ceiling = int(np.sum(volume >= hi * 0.999))

    interior = frame[(volume > lo * 1.001) & (volume < hi * 0.999)].copy()
    y = np.log(interior[volume_col].to_numpy(dtype=float))

    design = [
        np.ones(len(interior)),
        np.log(interior[et_col].to_numpy(dtype=float)),
        np.log(interior[area_col].to_numpy(dtype=float)),
    ]
    names = ["intercept", "log_et", "log_area"]
    multipliers: dict[str, dict[str, float]] = {}

    for column in categorical_cols:
        if column not in interior.columns:
            continue
        levels = sorted(interior[column].dropna().unique())[1:]  # first level is the reference
        for level in levels:
            design.append((interior[column] == level).to_numpy(dtype=float))
            names.append(f"{column}={level}")

    matrix = np.column_stack(design)
    coefficients, *_ = np.linalg.lstsq(matrix, y, rcond=None)
    fitted = matrix @ coefficients
    ss_res = float(np.sum((y - fitted) ** 2))
    ss_tot = float(np.sum((y - y.mean()) ** 2))
    r_squared = 1.0 - ss_res / ss_tot

    for name, coefficient in zip(names, coefficients):
        if "=" in name:
            column, level = name.split("=", 1)
            multipliers.setdefault(column, {})[level] = float(np.exp(coefficient))

    return AuditFinding(
        name="generative_structure",
        passed=r_squared < 0.8,
        headline=(
            f"a log-linear model of the target on the other columns explains "
            f"R2 = {r_squared:.3f} of its variance, with exponents "
            f"{coefficients[1]:.2f} on evapotranspiration and {coefficients[2]:.2f} on "
            f"field area, and the values are clipped at both ends "
            f"({at_floor} rows at the minimum, {at_ceiling} at the maximum)"
        ),
        evidence={
            "r_squared": r_squared,
            "exponent_on_et": float(coefficients[1]),
            "exponent_on_area": float(coefficients[2]),
            "intercept_multiplier": float(np.exp(coefficients[0])),
            "residual_sd_log": float(np.std(y - fitted)),
            "category_multipliers": multipliers,
            "rows_at_floor": at_floor,
            "rows_at_ceiling": at_ceiling,
            "floor_value": lo,
            "ceiling_value": hi,
            "rows_used": int(len(interior)),
        },
    )


# --------------------------------------------------------------------------
# Verdict
# --------------------------------------------------------------------------
def audit_candidate_target(frame: pd.DataFrame) -> TargetAuditResult:
    """Run every test and combine them into one decision."""
    findings = [
        test_dimensional_consistency(frame),
        test_driver_correlation(frame),
        test_marginal_distributions(frame),
        test_generative_structure(frame),
    ]

    dimensional = findings[0]
    failed = [f.name for f in findings if not f.passed]

    if not dimensional.passed:
        usable = False
        rationale = (
            "Rejected. The stated volume does not correspond to a physically "
            "possible irrigation depth once field area is taken into account, so "
            "the column cannot be an observed water requirement regardless of what "
            "the remaining tests show. Failing tests: " + ", ".join(failed) + "."
        )
    elif failed:
        usable = False
        rationale = (
            "Rejected. The column is dimensionally possible but fails "
            + ", ".join(failed)
            + ", which is inconsistent with a measured series."
        )
    else:
        usable = True
        rationale = (
            "No test detected a problem. The column remains a candidate target, "
            "but provenance documentation is still required before it is treated "
            "as observed ground truth."
        )

    for finding in findings:
        log.info("%-24s %s: %s", finding.name,
                 "PASS" if finding.passed else "FAIL", finding.headline)
    log.warning("verdict: usable_as_ground_truth = %s", usable)

    return TargetAuditResult(findings=findings, usable_as_ground_truth=usable, rationale=rationale)
